func exists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

// Ledger is a loaded catalog/ledger/ directory.
type Ledger struct {
	Dir     string
	Config  *Config
	Sources *Sources
	Legacy  *LegacyMap
	// Units holds each source's unit list, by source id.
	Units map[string][]Unit
	// Aliases holds every alias table, in file order.
	Aliases []*AliasTable
	// Published holds the lists the release job wrote, by role: all three, or none before the
	// first release publishes them.
	Published map[Role]*Published
}

// Load reads and checks every committed file of a ledger directory. It refuses a file the
// ledger does not define, so a role list cannot be added under another name (D4).
func Load(dir string, roleKeys map[string]RoleKeyFunc) (*Ledger, error) {
	if err := CheckLayout(dir); err != nil {
		return nil, err
	}
	l := &Ledger{Dir: dir, Units: map[string][]Unit{}}
	var err error
	if l.Config, err = LoadConfig(dir); err != nil {
		return nil, err
	}
	if l.Sources, err = LoadSources(dir); err != nil {
		return nil, err
	}
	if l.Legacy, err = LoadLegacyMap(dir); err != nil {
		return nil, err
	}
	var errs []error
	for _, src := range l.Sources.Sources {
		if _, ok := l.Config.Rules[src.ID]; !ok {
			errs = append(errs, fmt.Errorf("%s: source %q has no cut-points in %s", FileSources, src.ID, FileLedger))
		}
		if src.Units == "" {
			continue
		}
		rk, ok := roleKeys[src.ID]
		if !ok {
			errs = append(errs, fmt.Errorf("source %q has a unit list but no role-key rule in this build", src.ID))
			continue
		}
		units, _, err := ReadUnitList(filepath.Join(dir, filepath.FromSlash(src.Units)))
		if err != nil {
			errs = append(errs, err)
			continue
		}
		for i := range units {
			if err := units[i].Check(rk); err != nil {
				errs = append(errs, fmt.Errorf("%s: %w", src.Units, err))
				break
			}
		}
		if err := CheckMeasurementsUnique(units); err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", src.Units, err))
		}
		l.Units[src.ID] = units
	}
	for src := range l.Config.Rules {
		if l.Sources.Lookup(src) == nil {
			errs = append(errs, fmt.Errorf("%s: rules.%s names no source in %s", FileLedger, src, FileSources))
		}
	}
	if l.Legacy != nil {
		if l.Sources.Lookup(l.Legacy.Source) == nil {
			errs = append(errs, fmt.Errorf("%s: source %q is not in %s", FileLegacyMap, l.Legacy.Source, FileSources))
		} else if rule := l.Config.Rules[l.Legacy.Source]; len(rule.Legacy[SideFit]) == 0 || len(rule.Legacy[SideHeld]) == 0 {
			errs = append(errs, fmt.Errorf("%s: rules.%s needs legacy cut-points for FIT and HELD", FileLedger, l.Legacy.Source))
		}
		known := map[string]bool{}
		for _, u := range l.Units[l.Legacy.Source] {
			known[u.UnitID] = true
		}
		for _, id := range sortedKeys(l.Legacy.Units) {
			if !known[id] {
				errs = append(errs, fmt.Errorf("%s: unit %s is not in the %s unit list", FileLegacyMap, id, l.Legacy.Source))
				break
			}
		}
		got := l.Legacy.SetRoleKeySides(l.Units[l.Legacy.Source])
		if fmt.Sprint(got) != fmt.Sprint(l.Legacy.NewUnitsTakingSide) {
			errs = append(errs, fmt.Errorf("%s: new_units_taking_side does not list exactly the units outside the table whose role key holds legacy units", FileLegacyMap))
		}
	}
	if l.Aliases, err = LoadAliases(dir); err != nil {
		errs = append(errs, err)
	}
	if l.Published, err = LoadPublished(dir, l.Config, l.Units); err != nil {
		errs = append(errs, err)
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	return l, nil
}

// CheckAliasesAgainstBase is the second half of D4's merge-base check: the alias tables a
// candidate adds must equal those generated by pairing the identities the merge-base and
// candidate ingest tools give the same records. The committed unit lists are those tools'
// outputs on the pinned revision (the nightly check-generated requires it byte for byte), so
// when a source's revision is unchanged they are paired directly, with no source data. When
// the revision changed as well, identities cannot be paired across revisions, and a change
// that needs aliases is refused: change the revision and the identities in two pull requests.
func CheckAliasesAgainstBase(base, cand *Ledger) error {
	seen := map[string]bool{}
	for _, t := range base.Aliases {
		b, _ := CanonicalStruct(t)
		seen[string(b)] = true
	}
	added := []*AliasTable{}
	for _, t := range cand.Aliases {
		b, _ := CanonicalStruct(t)
		if !seen[string(b)] {
			added = append(added, t)
		}
	}
	var errs []error
	for _, src := range sortedKeys(base.Units) {
		bs, cs := base.Sources.Lookup(src), cand.Sources.Lookup(src)
		if cs == nil {
			errs = append(errs, fmt.Errorf("source %q was removed", src))
			continue
		}
		sameRev := fmt.Sprint(bs.Revision) == fmt.Sprint(cs.Revision)
		gen, err := GenerateAliases(src, "", base.Units[src], cand.Units[src])
		switch {
		case err != nil && sameRev:
			errs = append(errs, fmt.Errorf("%s: %w", src, err))
		case err != nil:
			// A new revision: base units missing from it are reported by CheckAgainstBase.
		case !sameRev && len(gen.Alias) > 0:
			errs = append(errs, fmt.Errorf("%s: the source revision and %d identities changed together; change them in separate pull requests so the aliases can be generated", src, len(gen.Alias)))
		default:
			if err := CheckAliasesGenerated(src, added, gen); err != nil {
				errs = append(errs, err)
			}
		}
	}
	return errors.Join(errs...)
}

// allowed matches the files a ledger directory may hold, by path relative to it.
var allowed = []*regexp.Regexp{
	regexp.MustCompile(`^(ledger|sources|legacy-map)\.yaml$`),
	regexp.MustCompile(`^README\.md$`),
	regexp.MustCompile(`^legacy-points\.jsonl\.gz$`),
	regexp.MustCompile(`^units/[a-z0-9-]+\.jsonl\.gz$`),
	regexp.MustCompile(`^reports/[a-z0-9-]+\.yaml$`),
	regexp.MustCompile(`^aliases/[a-z0-9-]+-[0-9]+\.yaml$`),
	regexp.MustCompile(`^published/(fit|anchor|report)\.yaml$`),
}

// CheckLayout refuses any file under dir that the ledger does not define, and any symbolic
// link. The only files that may list roles are published/{fit,anchor,report}.yaml; the legacy
// labels of legacy-map.yaml are sides, not roles (D4).
func CheckLayout(dir string) error {
	var errs []error
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		rel = filepath.ToSlash(rel)
		if d.Type()&fs.ModeSymlink != 0 {
			errs = append(errs, fmt.Errorf("%s: a symbolic link; the ledger holds plain files", rel))
			return nil
		}
		if d.IsDir() {
			return nil
		}
		for _, re := range allowed {
			if re.MatchString(rel) {
				return nil
			}
		}
		errs = append(errs, fmt.Errorf("%s: not a ledger file; the ledger holds only the files catalog/ledger/README.md lists", rel))
		return nil
	})
	if err != nil {
		return err
	}
	return errors.Join(errs...)
}

// unitRef matches an identifier a unit could be named by: 16 or more hex digits.
var unitRef = regexp.MustCompile(`\b[0-9a-fA-F]{16,64}\b`)

// roleWord matches a role or a legacy label used as a value or as a key: after ':', '=', ',',
// a tab or a list dash, and before the end of the value; or as a key that opens a list or a
// mapping. So "role: held", "{\"role\":\"held\"}", "abc…,held", "held:" and "- FIT" match,
// and prose such as "the report (not redistributed)" does not.
var roleWord = regexp.MustCompile(`(?i)([:=,\t-]\s*["']?(fit|select|validate|held|anchor|report)["']?\s*([,}\]#\t]|$))|(^\s*["']?(fit|select|validate|held|anchor|report)["']?\s*:\s*(\[|\{|$))`)

// LegacyFiles are the two committed files that may pair a unit with a legacy label (D4).
var LegacyFiles = []string{"catalog/ledger/" + FileLegacyMap, "catalog/ledger/legacy-points.jsonl.gz"}

// CheckNoRoles is D4's check that no committed file lists roles. It refuses any line that
// names both a unit-like identifier (16 or more hex digits) and a role or legacy label, in
// every file of files (paths relative to root), except the three published lists and the two
// legacy files. Gzipped files are read decompressed. skip names paths not to scan, for test
// fixtures that hold roles on purpose as known-bad inputs.
func CheckNoRoles(root string, files []string, skip func(string) bool) error {
	var errs []error
	for _, rel := range files {
		if (skip != nil && skip(rel)) || contains(LegacyFiles, rel) || publishedList.MatchString(rel) {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if strings.HasSuffix(rel, ".gz") {
			if raw, err = gunzip(raw); err != nil {
				errs = append(errs, fmt.Errorf("%s: %w", rel, err))
				continue
			}
		}
		// A role used as a key that opens a list or mapping ("held:" then "- <id>") pairs the
		// role with the identifiers below it, so a file with such a key and any identifier is
		// refused.
		opened := 0
		for i, line := range bytes.Split(raw, []byte("\n")) {
			if opened == 0 && roleKeyLine.Match(line) {
				opened = i + 1
			}
			if unitRef.Match(line) && (roleWord.Match(line) || opened > 0) {
				errs = append(errs, fmt.Errorf("%s:%d: pairs an identifier with a role; roles are computed by the seed-holding jobs, and only catalog/ledger/published/{fit,anchor,report}.yaml list them (D4)", rel, i+1))
				break
			}
		}
	}
	return errors.Join(errs...)
}

var roleKeyLine = regexp.MustCompile(`(?i)^\s*["']?(fit|select|validate|held|anchor|report)["']?\s*:\s*(\[|\{|$)`)

var publishedList = regexp.MustCompile(`^catalog/ledger/published/(fit|anchor|report)\.yaml$`)

// AliasTable maps old unit identifiers and role keys to new ones after a change to how a
// source's identifying fields or role keys are computed (design §10.2). An aliased unit keeps
// its role.
type AliasTable struct {
	Kind   string  `yaml:"kind"` // "AliasTable"
	Source string  `yaml:"source"`
	Reason string  `yaml:"reason"`
	Alias  []Alias `yaml:"aliases"`
}

// Alias is one old unit's new identity.
type Alias struct {
	OldUnitID  string `yaml:"old_unit_id"`
	NewUnitID  string `yaml:"new_unit_id"`
	OldRoleKey string `yaml:"old_role_key"`
	NewRoleKey string `yaml:"new_role_key"`
}

// LoadAliases reads every alias table under dir/aliases, in file-name order.
func LoadAliases(dir string) ([]*AliasTable, error) {
	paths, err := filepath.Glob(filepath.Join(dir, DirAliases, "*.yaml"))
	if err != nil {
		return nil, err
	}
	sort.Strings(paths)
	var out []*AliasTable
	for _, p := range paths {
		var t AliasTable
		if err := decodeStrictFile(p, &t); err != nil {
			return nil, err
		}
		if t.Kind != "AliasTable" || t.Source == "" || t.Reason == "" || len(t.Alias) == 0 {
			return nil, fmt.Errorf("%s: an alias table has kind AliasTable, a source, a reason and at least one alias", p)
		}
		for i, a := range t.Alias {
			for _, v := range []string{a.OldUnitID, a.NewUnitID, a.OldRoleKey, a.NewRoleKey} {
				if !hex64.MatchString(v) {
					return nil, fmt.Errorf("%s: aliases[%d]: every identifier is a SHA-256", p, i)
				}
			}
		}
		out = append(out, &t)
	}
	return out, nil
}

// CheckAgainstBase is D4's check against the ledger at the pull request's merge base. Every
// unit at the base must still exist with the same role key, or an alias table in the candidate
// must map it to a unit of the candidate with the role key the alias names.
//
// The partition version, the seed record and the cut-points change only together, as one new
// partition version: the next number, with a seed record that is created and whose SHA-256
// differs from the base's, and the cut-points the new version states. Nobody approves it in the pull request
// (no check waits on a person). What keeps D7 is the seed itself: a ledger owner creates the
// secret at release time, and every seed-holding job refuses a secret whose SHA-256 is not the
// one the record states (NewAssigner), so a record without its secret draws no role.
func CheckAgainstBase(base, cand *Ledger) error {
	var errs []error
	bc, cc := base.Config, cand.Config
	newVersion := cc.PartitionVersion != bc.PartitionVersion
	if newVersion {
		switch {
		case cc.PartitionVersion != bc.PartitionVersion+1:
			errs = append(errs, fmt.Errorf("partition_version changed from %d to %d; a new partition version is the next number, %d", bc.PartitionVersion, cc.PartitionVersion, bc.PartitionVersion+1))
		case !cc.Seed.Created():
			errs = append(errs, fmt.Errorf("partition_version changed from %d to %d with no seed record; a new partition version records its new seed (D7)", bc.PartitionVersion, cc.PartitionVersion))
		case cc.Seed.SHA256 == bc.Seed.SHA256:
			// A seed's identity is its SHA-256: what every seed-holding job checks the secret
			// against. A record that differs only in who generated it, when, or who owns the
			// rotation names the same secret, so it draws the same roles.
			errs = append(errs, fmt.Errorf("partition_version changed from %d to %d with the seed record's sha256 unchanged; a new partition version is drawn from a new seed, and a seed is identified by its SHA-256, not by who generated it or when (D7)", bc.PartitionVersion, cc.PartitionVersion))
		}
	}
	if !newVersion && bc.Seed.Created() && bc.Seed != cc.Seed {
		errs = append(errs, errors.New("seed record changed; a seed is rotated only with a new partition version"))
	}
	for src, br := range bc.Rules {
		cr, ok := cc.Rules[src]
		if !newVersion && (!ok || fmt.Sprint(br) != fmt.Sprint(cr)) {
			errs = append(errs, fmt.Errorf("rules.%s changed; cut-points change only with a new partition version", src))
		}
	}
	if base.Legacy != nil {
		if cand.Legacy == nil {
			errs = append(errs, errors.New("legacy-map.yaml was removed"))
		} else {
			for id, s := range base.Legacy.Units {
				if cs, ok := cand.Legacy.Units[id]; ok && cs != s {
					errs = append(errs, fmt.Errorf("legacy unit %s moved from %s to %s", id, s, cs))
				}
			}
		}
	}
	alias := map[string]Alias{}
	for _, t := range cand.Aliases {
		for _, a := range t.Alias {
			alias[t.Source+"/"+a.OldUnitID] = a
		}
	}
	for _, src := range sortedKeys(base.Units) {
		cu := map[string]string{}
		for _, u := range cand.Units[src] {
			cu[u.UnitID] = u.RoleKey
		}
		missing := 0
		for _, u := range base.Units[src] {
			if rk, ok := cu[u.UnitID]; ok {
				if rk != u.RoleKey {
					if a, ok := alias[src+"/"+u.UnitID]; !ok || a.OldRoleKey != u.RoleKey || a.NewRoleKey != rk || a.NewUnitID != u.UnitID {
						errs = append(errs, fmt.Errorf("%s unit %s: role key changed from %s to %s with no alias", src, u.UnitID, u.RoleKey, rk))
					}
				}
				continue
			}
			a, ok := alias[src+"/"+u.UnitID]
			if !ok {
				missing++
				if missing <= 5 {
					errs = append(errs, fmt.Errorf("%s unit %s is at the merge base but not in the candidate, and no alias table maps it", src, u.UnitID))
				}
				continue
			}
			if a.OldRoleKey != u.RoleKey || cu[a.NewUnitID] != a.NewRoleKey {
				errs = append(errs, fmt.Errorf("%s unit %s: its alias names role keys %s -> %s, but the units hold %s -> %s", src, u.UnitID, a.OldRoleKey, a.NewRoleKey, u.RoleKey, cu[a.NewUnitID]))
			}
		}
		if missing > 5 {
			errs = append(errs, fmt.Errorf("%s: %d units in all are missing with no alias", src, missing))
		}
	}
	return errors.Join(errs...)
}
