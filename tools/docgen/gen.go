// outDir is where generated pages live, relative to the repository root. The site
// includes them with the snippets extension; nothing else should write there.
const outDir = "docs/contracts/generated"

// enumDirs are the packages whose typed string constants form a closed vocabulary.
var enumDirs = []string{
	"contracts/vocab",
	"contracts/kernel",
	"contracts/spec/model",
	"contracts/spec/deployment",
	"contracts/spec/workload",
	"contracts/spec/acceptance",
	"contracts/spec/measurement",
	"contracts/spec/router",
	"contracts/spec/fields",
	"contracts/spec/result",
	"contracts/spec/trace",
	"contracts/spec/pointrecord",
	"contracts/metrics",
}

type file struct {
	path    string // relative to the repository root
	content []byte
}

// generate returns every generated file, in a stable order. root is the repository root.
func generate(root string) ([]file, error) {
	var out []file
	enums, err := enumFiles(root)
	if err != nil {
		return nil, err
	}
	out = append(out, enums...)
	out = append(out, metricsTable())
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out, nil
}

const header = "<!-- Generated by `go run ./tools/docgen`. Do not edit. -->\n\n"

// enumFiles writes one file per closed vocabulary: the values of every constant declared
// with that type, in declaration order. Declaration order is kept because the source
// groups related members, and an alphabetical list would scatter them.
func enumFiles(root string) ([]file, error) {
	var out []file
	for _, dir := range enumDirs {
		pkg, consts, err := typedStringConsts(filepath.Join(root, dir))
		if err != nil {
			return nil, err
		}
		types := make([]string, 0, len(consts))
		for t := range consts {
			types = append(types, t)
		}
		sort.Strings(types)
		for _, t := range types {
			var b bytes.Buffer
			b.WriteString(header)
			vals := make([]string, 0, len(consts[t]))
			for _, v := range consts[t] {
				if v == "" {
					vals = append(vals, "`\"\"`")
					continue
				}
				vals = append(vals, "`"+v+"`")
			}
			b.WriteString(strings.Join(vals, " · "))
			b.WriteString("\n")
			out = append(out, file{
				path:    filepath.ToSlash(filepath.Join(outDir, "enum", pkg+"."+t+".md")),
				content: b.Bytes(),
			})
		}
	}
	return out, nil
}

// typedStringConsts parses the non-test Go files in dir and returns, for each named type,
// the string values of the constants declared with that type explicitly.
func typedStringConsts(dir string) (string, map[string][]string, error) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", nil, err
	}
	var names []string
	for _, e := range entries {
		n := e.Name()
		if strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	pkg := ""
	out := map[string][]string{}
	for _, n := range names {
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, 0)
		if err != nil {
			return "", nil, err
		}
		pkg = f.Name.Name
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			for _, s := range gd.Specs {
				vs := s.(*ast.ValueSpec)
				id, ok := vs.Type.(*ast.Ident)
				if !ok || len(vs.Values) != len(vs.Names) {
					continue
				}
				for _, v := range vs.Values {
					lit, ok := v.(*ast.BasicLit)
					if !ok || lit.Kind != token.STRING {
						continue
					}
					s, err := strconv.Unquote(lit.Value)
					if err != nil {
						return "", nil, err
					}
					out[id.Name] = append(out[id.Name], s)
				}
			}
		}
	}
	return pkg, out, nil
}

// metricsTable writes the metric registry (contracts/metrics) as one table, so the page a
// reader trusts lists exactly the definitions the code holds (DEV-8).
func metricsTable() file {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("| Identifier | Formula | Statistic | Population | Window | Unit | Denominator | Unfinished | Scopes | Aggregates | Meaning |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, d := range metrics.All() {
		st := string(d.Statistic)
		if d.PercentileMethod != "" {
			st += " (" + string(d.PercentileMethod) + ")"
		}
		denom := "-"
		if d.Denominator != "" {
			denom = string(d.Denominator)
		}
		scopes := make([]string, len(d.Scopes))
		for i, sc := range d.Scopes {
			scopes[i] = string(sc)
		}
		aggs := "-"
		if len(d.Aggregates) > 0 {
			l := make([]string, len(d.Aggregates))
			for i, a := range d.Aggregates {
				l[i] = string(a)
			}
			aggs = strings.Join(l, ", ")
		}
		desc := d.Description
		if d.Follows != "" {
			desc += " Follows " + d.Follows + "."
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | `%s` | `%s` | %s | %s | %s | %s | %s | %s |\n",
			d.ID, d.Formula, st, d.Population, d.Window, d.Unit, denom, d.Unfinished,
			strings.Join(scopes, ", "), aggs, desc)
	}
	return file{path: outDir + "/metrics.md", content: b.Bytes()}
}
